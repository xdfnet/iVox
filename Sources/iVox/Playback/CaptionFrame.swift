import Foundation

// 播报字幕的一帧：歌词式字幕要的「这一页的句子」与「念到第几句」。

/// 字幕的一帧（歌词式）。
///
/// **为什么不是「一句」**：像音乐播放软件的歌词那样，屏上留着**一段**文字，
/// 正在念到的那句亮着（卡拉OK式逐字推进），其余暗着。
/// 所以字幕这一路要的不是「当前这句」，而是「这一页的句子 + 念到第几句」。
struct CaptionFrame: Sendable {
    /// 当前页的句子（按念的顺序）
    let lines: [String]
    /// 正在念的是第几句（`lines` 的下标）
    let index: Int
}
